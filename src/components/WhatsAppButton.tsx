import { getWhatsAppLink } from "@/lib/settings";

interface WhatsAppButtonProps {
  /** WhatsApp number in international format without "+", e.g. "919999999999". */
  phoneNumber: string;
  /** Optional pre-filled message, e.g. mentioning the current product. */
  message?: string;
  /** "floating" pins to the bottom-right corner; "inline" renders as a normal block button. */
  variant?: "floating" | "inline";
  className?: string;
}

export default function WhatsAppButton({
  phoneNumber,
  message,
  variant = "inline",
  className = "",
}: WhatsAppButtonProps) {
  const href = getWhatsAppLink(phoneNumber, message);

  if (variant === "floating") {
    return (
      <a
        href={href}
        target="_blank"
        rel="noopener noreferrer"
        aria-label="Chat with us on WhatsApp"
        className="fixed bottom-5 right-5 z-40 flex h-14 w-14 items-center justify-center rounded-full bg-[#25D366] text-white shadow-lg transition-transform hover:scale-105"
      >
        <WhatsAppIcon className="h-7 w-7" />
      </a>
    );
  }

  return (
    <a
      href={href}
      target="_blank"
      rel="noopener noreferrer"
      className={`inline-flex items-center justify-center gap-2 rounded-md bg-[#25D366] px-5 py-3 text-sm font-semibold text-white transition-colors hover:bg-[#1ebc59] ${className}`}
    >
      <WhatsAppIcon className="h-5 w-5" />
      Chat on WhatsApp
    </a>
  );
}

